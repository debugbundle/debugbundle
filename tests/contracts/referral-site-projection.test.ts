import { REFERRAL_OFFERS_RUNTIME_CONTRACT } from "../../packages/referrals/src/offer-runtime-contract.js";
import { existsSync } from "node:fs";
import { readFile } from "node:fs/promises";
import { join } from "node:path";
import { expect, it } from "vitest";
const projection = join(
  process.env["DEBUGBUNDLE_SITE_ROOT"] ?? "site",
  "src/generated/offer-policy.ts"
);
it("keeps the canonical commercial policy safe for browser projection", async () => {
  expect(await readFile("packages/referrals/src/programme-policy.ts", "utf8")).not.toMatch(
    /node:crypto|process\.env|storage\/|stripe/
  );
});
it.skipIf(!existsSync(projection) && process.env["REFERRAL_SITE_PROJECTION_REQUIRED"] !== "1")(
  "keeps the independent site on the exact canonical offer contract",
  async () => {
    const [source, copy] = await Promise.all([
      readFile("packages/referrals/src/programme-policy.ts", "utf8"),
      readFile(projection, "utf8")
    ]);
    expect(copy).toBe(
      `// Generated by core: make referral-site-contracts. Do not edit.\n${source}`
    );
  }
);

it("declares the immutable reader floor for saved programme obligations", () => {
  expect(REFERRAL_OFFERS_RUNTIME_CONTRACT).toBe("referral-offers-v1");
});

it.skipIf(!existsSync(join(process.env["DEBUGBUNDLE_SITE_ROOT"] ?? "site", "public/openapi.json")))(
  "keeps generated public API and automation artifacts identical to their source contracts",
  async () => {
    const { buildMachineReadableArtifacts, buildReferenceData } =
      await import("../../scripts/public-site-artifacts.js");
    const siteRoot = process.env["DEBUGBUNDLE_SITE_ROOT"] ?? "site";
    for (const artifact of await buildMachineReadableArtifacts()) {
      const published = await readFile(join(siteRoot, "public", artifact.routePath), "utf8");
      expect(published, artifact.routePath).toBe(artifact.content);
    }
    expect(
      JSON.parse(await readFile(join(siteRoot, "public/reference-data.json"), "utf8"))
    ).toEqual(await buildReferenceData());
  }
);
