const severity = { critical: 0, high: 1, medium: 2, low: 3, unknown: 4 };
/** Stable, evidence-linked plans. Configuration changes remain human/agent review
 * tasks; no mutation payload or suppression decision is generated by the model. */
export function planReview(facts: ReviewFacts, raw: ReviewContext): ReviewPlan[] {
  const context = ReviewContextSchema.parse(raw);
  const signals = new Map(context.signals.map((s) => [s.source_ref, s]));
  const active = facts.sources
    .filter((s) => !["resolved", "snoozed", "dismissed", "healthy"].includes(s.status))
    .sort(
      (a, b) =>
        severity[a.severity] - severity[b.severity] ||
        a.ref.localeCompare(b.ref, "en", { numeric: true })
    );
  const seen = new Set<string>();
  const groups: (typeof active)[] = [];
  for (const source of active) {
    if (seen.has(source.ref)) continue;
    const group = [source];
    seen.add(source.ref);
    // Only directly recorded links within selected evidence group work. Bound
    // each plan to the existing provider reference ceiling without losing others.
    for (const other of active) {
      if (group.length >= 5 || seen.has(other.ref)) continue;
      const opportunity =
        source.kind === "improvement" ? source : other.kind === "improvement" ? other : null;
      const duplicateWork =
        opportunity &&
        (source.kind === "incident" || other.kind === "incident") &&
        ["recurring_incident", "post_deploy_regression"].includes(
          signals.get(opportunity.ref)?.detector ?? ""
        );
      if (
        duplicateWork &&
        ((source.related_refs ?? []).includes(other.ref) ||
          (other.related_refs ?? []).includes(source.ref) ||
          (signals.get(source.ref)?.related_refs ?? []).includes(other.ref) ||
          (signals.get(other.ref)?.related_refs ?? []).includes(source.ref))
      ) {
        group.push(other);
        seen.add(other.ref);
      }
    }
    groups.push(group);
  }
  const rank = (group: typeof active): number =>
    Math.min(...group.map((s) => severity[s.severity]));
  const recurring = (group: typeof active): boolean =>
    group.some((s) =>
      ["recurring_incident", "post_deploy_regression"].includes(signals.get(s.ref)?.detector ?? "")
    );
  const activeFailure = (group: typeof active): boolean =>
    group.some(
      (s) =>
        s.kind === "incident" ||
        s.kind === "health" ||
        ["recurring_incident", "post_deploy_regression", "slow_request"].includes(
          signals.get(s.ref)?.detector ?? ""
        )
    );
  const measuredImpact = (group: typeof active): boolean =>
    facts.analytics.coverage === "complete" &&
    group.some((s) =>
      signals
        .get(s.ref)
        ?.measurements.some(
          (m) => m.key === "affected_sessions" && m.basis === "period" && m.value > 0
        )
    );
  groups.sort(
    (a, b) =>
      rank(a) - rank(b) ||
      Number(activeFailure(b)) - Number(activeFailure(a)) ||
      Number(recurring(b)) - Number(recurring(a)) ||
      Number(measuredImpact(b)) - Number(measuredImpact(a)) ||
      a[0]!.ref.localeCompare(b[0]!.ref, "en", { numeric: true })
  );
  return groups.slice(0, 5).map((group, index) => {
    const source = group[0]!,
      signal = signals.get(source.ref);
    const failure = group.some(
      (s) =>
        s.kind === "incident" ||
        (s.kind === "improvement" && ["critical", "high"].includes(s.severity)) ||
        signals.get(s.ref)?.protected_failure === true ||
        s.status === "regressed" ||
        ["recurring_incident", "post_deploy_regression", "slow_request"].includes(
          signals.get(s.ref)?.detector ?? ""
        )
    );
    const measured =
      facts.analytics.coverage === "complete" &&
      signal?.window !== null &&
      signal?.window !== undefined &&
      Date.parse(signal.window.ends_at) <= Date.parse(facts.cutoff_at) &&
      Date.parse(signal.window.starts_at) < Date.parse(signal.window.ends_at) &&
      (signal?.measurements.some(
        (m) =>
          ["sessions_entered", "unique_sessions", "current_sessions", "total_sessions"].includes(
            m.key
          ) &&
          m.value > 0 &&
          m.basis === "period"
      ) ??
        false);
    const noise =
      !failure &&
      source.kind === "improvement" &&
      ["warning_hotspot", "request_failure_pattern"].includes(signal?.detector ?? "");
    const action = failure
      ? "investigate_failure"
      : source.kind === "analytics"
        ? measured
          ? "improve_flow"
          : "collect_evidence"
        : noise
          ? "review_noise"
          : source.kind === "health"
            ? "investigate_failure"
            : "collect_evidence";
    const selected: ReviewPlan["controls"] = [];
    if (noise) selected.push(controls.capture_rules, controls.capture_policy);
    // Low-information incident metadata cannot establish harmlessness. Offer
    // the existing evidence-first suggestion workflow without reclassifying it.
    if (
      source.kind === "incident" &&
      ["low", "medium"].includes(source.severity) &&
      source.status !== "regressed"
    )
      selected.push(controls.capture_rules, controls.capture_policy);
    if (
      context.configuration.alerts.some((a) =>
        a.repeated_source_refs.some((r) => group.some((s) => s.ref === r))
      )
    )
      selected.push(controls.alert_delivery);
    const linkedRule = context.configuration.rules.find((r) =>
      r.source_refs.some((ref) => group.some((s) => s.ref === ref))
    );
    const ruleCheck = selected.find((c) => c.control === "capture_rules");
    if (linkedRule && ruleCheck) {
      const state = !linkedRule.enabled
        ? "disabled"
        : linkedRule.expires_at && Date.parse(linkedRule.expires_at) <= Date.parse(facts.cutoff_at)
          ? "expired"
          : "enabled";
      selected[selected.indexOf(ruleCheck)] = {
        ...ruleCheck,
        check: `One linked rule snapshot: ${linkedRule.action} (${state}). ${ruleCheck.check}`
      };
    }
    const repeatedAlert = context.configuration.alerts.find((a) =>
      a.repeated_source_refs.some((ref) => group.some((s) => s.ref === ref))
    );
    const alertCheck = selected.find((c) => c.control === "alert_delivery");
    if (repeatedAlert && alertCheck)
      selected[selected.indexOf(alertCheck)] = {
        ...alertCheck,
        check: `Observed cooldown: ${repeatedAlert.cooldown_seconds}s (${repeatedAlert.cooldown_scope}); email aggregation: ${repeatedAlert.aggregation_window_seconds === null ? "unavailable" : `${repeatedAlert.aggregation_window_seconds}s`}. ${alertCheck.check}`
      };
    const origins = new Set(group.map((s) => s.origin_project_id));
    const currentPolicy = context.configuration.origins.find(
      (o) => o.origin_project_id === source.origin_project_id
    );
    const policyCheck = selected.find((c) => c.control === "capture_policy");
    if (policyCheck) {
      const index = selected.indexOf(policyCheck);
      selected[index] = {
        ...policyCheck,
        check: currentPolicy?.preset
          ? `Current capture: ${currentPolicy.preset}; logs ${currentPolicy.logs ?? "unknown"}; requests ${currentPolicy.requests ?? "unknown"}. ${policyCheck.check}`
          : `Effective capture settings are unavailable in this snapshot. ${policyCheck.check}`
      };
    }
    if (
      noise &&
      context.configuration.origins.some(
        (o) => origins.has(o.origin_project_id) && o.sensitivity === "verbose"
      )
    )
      selected.push(controls.improvement_detection);
    if (
      (context.configuration.active_probes ?? 0) > 0 ||
      context.configuration.origins.some(
        (o) =>
          origins.has(o.origin_project_id) && o.preset === "investigative" && o.diagnostic_capture
      )
    )
      selected.push(controls.temporary_diagnostics);
    if (noise && context.configuration.coverage !== "complete") selected.push(controls.sdk_local);
    const reason = failure
      ? "Active failure or recorded recurrence/regression takes priority; frequency and linkage do not establish its cause."
      : source.kind === "analytics"
        ? measured
          ? "A measured flow opportunity has an observed denominator; inspect comparable segments before choosing a change."
          : "The flow signal lacks complete comparable measurement; collect the missing evidence before proposing a change."
        : noise
          ? "A repeated warning or contextual failure warrants an expected-behaviour review. Frequency alone does not establish harmless noise."
          : "The selected observation needs a bounded investigation before a change can be justified.";
    return ReviewPlanSchema.parse({
      ref: `p${index + 1}`,
      action,
      source_refs: group
        .map((s) => s.ref)
        .sort((a, b) => a.localeCompare(b, "en", { numeric: true })),
      reason,
      inspection: noise
        ? "Inspect retained evidence to establish whether the behaviour is expected, user-impacting or redundant. Prefer fixing unexpected behaviour at its source. Reuse incident-based capture-rule suggestions and check current matching rules before considering tuning verified expected context."
        : source.kind === "analytics"
          ? "Inspect the denominator, sampling, affected flow, instrumentation and comparable segments. Validate recorded relationships without inferring a shared cause."
          : source.kind === "health"
            ? "Compare the selected monitor's failing and last successful observation windows and response evidence. Check whether failures persist independently when overlapping monitors recover; missing observations remain unknown and overlap does not establish an account outage."
            : "Inspect linked incident and opportunity evidence and the authorised execution path. Reproduce the observed symptom and test the tentative explanation before changing code.",
      verification: noise
        ? "Observe comparable traffic and reproduce the expected pattern plus genuine failures. Confirm useful context and critical/regression visibility remain; revert a change if evidence is lost."
        : source.kind === "analytics"
          ? "Reproduce the affected flow, add a regression check and compare subsequent observations with equivalent sampling, denominator and capture policy. Lower traffic or missing data does not prove improvement."
          : source.kind === "health"
            ? "Repeat the affected monitor and previously successful checks over comparable observation windows. Verify current recovery and recurrence without reducing required coverage; a quiet period, missing observation or resolved status alone does not prove a fix."
            : "Add a regression check and observe the same failure path with comparable traffic and capture settings. Verify current recovery and recurrence; a quiet period, deleted source or resolved status alone does not prove a fix.",
      controls: selected
    });
  });
}
export function planningDigest(facts: ReviewFacts, context: ReviewContext): string {
  const parsed = ReviewContextSchema.parse(context);
  const stable = {
    ...parsed,
    configuration: {
      ...parsed.configuration,
      origins: parsed.configuration.origins.map(({ policy_at: _at, ...o }) => {
        void _at;
        return o;
      })
    }
  };
  return createHash("sha256")
    .update(JSON.stringify({ base: reviewEvidenceDigest(facts), context: stable }))
    .digest("hex");
}
export function validatePlannedGuidance(
  facts: ReviewFacts,
  context: ReviewContext,
  raw: unknown,
  identities: readonly string[] = []
): ReviewGuidance {
  const guidance = validateReviewGuidance(facts, raw, identities);
  const keys = new Set(planReview(facts, context).map((p) => [...p.source_refs].sort().join()));
  const investigations = new Set<string>();
  for (const item of guidance.investigations) {
    if (!keys.has([...item.evidence_refs].sort().join()))
      throw new Error("review_unplanned_guidance");
    // Different source labels or checklist order do not make repeated generic
    // checks useful. Normalise a copy without changing the returned guidance.
    const checks = JSON.stringify(
      item.checks.map((c) => c.trim().replace(/\s+/gu, " ").toLowerCase()).sort()
    );
    if (investigations.has(checks)) throw new Error("review_duplicate_guidance");
    investigations.add(checks);
    // Configuration decisions and safeguards belong to server templates. Free
    // provider prose may investigate evidence, never prescribe capture mutation.
    // Match within a field/clause: a bounded code change followed by comparable
    // capture observations does not prescribe changing the capture settings.
    if (
      [item.title, item.hypothesis ?? "", ...item.checks].some((text) =>
        /\b(?:demote|suppress|disable|silence|beforeSend|turn off)\b|\b(?:drop|sample)\s+(?:all|the|these|matching|events|errors|failures|requests|logs)\b|\b(?:increase|decrease|change|set|adjust|extend|shorten|configure)\b[^.!?;,\n]{0,80}\b(?:cooldown|sampling|capture|threshold|filter|rules?)\b/iu.test(
          text
        )
      )
    )
      throw new Error("review_unsafe_configuration_guidance");
  }
  return guidance;
}
