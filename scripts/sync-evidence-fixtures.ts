import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve, sep } from "node:path";
import { toInputJsonSchema } from "../packages/shared-types/src/json-schema.js";

import {
  EventEnvelopeSchema,
  EVENT_INGESTION_MAX_BODY_BYTES,
  EVENT_ENVELOPE_MAX_WIRE_BYTES,
  intersectEvidenceCapabilities
} from "../packages/shared-types/src/index.js";
import { evidenceWireFixtures, evidenceCapabilityFixtures } from "./evidence-wire-fixtures.js";

// SDK fixtures are vendored from the accepting contract. Semantic refinements
// (UTF-8 byte totals, graph reachability and temporal admission) also need the
// shared conformance corpus; JSON Schema cannot express those invariants.
const schema = {
  ...toInputJsonSchema(EventEnvelopeSchema, "draft-7"),
  $id: "https://debugbundle.com/schemas/event-envelope.json",
  $comment:
    "Generated by scripts/sync-evidence-fixtures.ts from EventEnvelopeSchema. Do not edit by hand."
};
const content = `${JSON.stringify(schema, null, 2)}\n`;
const corpus = {
  version: 1,
  transport: {
    max_body_bytes: EVENT_INGESTION_MAX_BODY_BYTES,
    max_event_wire_bytes: EVENT_ENVELOPE_MAX_WIRE_BYTES
  },
  events: evidenceWireFixtures(),
  capabilities: evidenceCapabilityFixtures,
  json_sizes: [
    null,
    true,
    false,
    'é/\u2028\n"',
    0,
    -0,
    1,
    -1.23,
    1000,
    1e-6,
    1.2345e-6,
    1e-7,
    1.2345678901234567e-5,
    1e20,
    1.2345e20,
    1e21,
    5e-324,
    1.7976931348623157e308,
    9007199254740992,
    1000000000000000100,
    { values: [1e-7, 1e20], nested: { empty: [] } }
  ].map((value) => ({ value, bytes: Buffer.byteLength(JSON.stringify(value), "utf8") }))
};
for (const fixture of corpus.events) {
  const result = EventEnvelopeSchema.safeParse(fixture.event);
  if (result.success !== fixture.valid)
    throw new Error(
      `Evidence fixture disagrees with canonical schema: ${fixture.id}; ${result.success ? "unexpected acceptance" : result.error.issues.map((issue) => `${issue.path.join(".")}: ${issue.message}`).join("; ")}`
    );
}
for (const fixture of corpus.capabilities) {
  if (
    JSON.stringify(intersectEvidenceCapabilities([fixture.input]).features) !==
    JSON.stringify(fixture.features)
  )
    throw new Error(`Evidence capability fixture disagrees with canonical schema: ${fixture.id}`);
}
const corpusContent = `${JSON.stringify(corpus, null, 2)}\n`;
const targets: Record<string, string> = {
  rust: "sdks/debugbundle-rust/tests/fixtures/event-envelope.schema.json",
  php: "sdks/debugbundle-php/tests/fixtures/event-envelope.schema.json",
  python: "sdks/debugbundle-python/tests/fixtures/event-envelope.schema.json",
  ruby: "sdks/debugbundle-ruby/spec/fixtures/event-envelope.schema.json",
  java: "sdks/debugbundle-java/debugbundle-java-core/src/test/resources/evidence/event-envelope.schema.json",
  go: "sdks/debugbundle-go/internal/evidence/testdata/event-envelope.schema.json",
  dotnet: "sdks/debugbundle-dotnet/tests/fixtures/event-envelope.schema.json",
  swift: "sdks/debugbundle-swift/Tests/DebugBundleTests/Fixtures/event-envelope.schema.json",
  react_native: "sdks/debugbundle-react-native/tests/fixtures/event-envelope.schema.json",
  android:
    "sdks/debugbundle-android/debugbundle-android-core/src/test/resources/evidence/event-envelope.schema.json"
};
const selected = (process.env["SDK_FIXTURE_TARGETS"] ?? "").split(",").filter(Boolean);
const outputIndex = process.argv.indexOf("--schema-output");
const output = outputIndex < 0 ? undefined : process.argv[outputIndex + 1];
if (
  outputIndex >= 0 &&
  (!output?.startsWith(".tmp/evidence-release/") ||
    !resolve(output).startsWith(resolve(".tmp/evidence-release") + sep) ||
    selected.length > 0)
)
  throw new Error("Isolated schema output requires .tmp/evidence-release/ and no SDK targets");
const paths = [
  output ?? "tests/fixtures/evidence/event-envelope.schema.json",
  ...selected.map((name) => {
    const target = targets[name];
    if (!target) throw new Error(`Unknown SDK fixture target: ${name}`);
    return target;
  })
];
const generated: Array<readonly [string, string]> = paths.flatMap(
  (path) =>
    [
      [path, content],
      [resolve(dirname(path), "evidence-wire-cases.json"), corpusContent]
    ] as const
);
if (selected.includes("php"))
  generated.push(["sdks/debugbundle-php/src/event-envelope.schema.json", content]);
if (selected.includes("python"))
  generated.push(["sdks/debugbundle-python/src/debugbundle/event-envelope.schema.json", content]);
if (selected.includes("ruby"))
  generated.push(["sdks/debugbundle-ruby/lib/debugbundle/event-envelope.schema.json", content]);
if (selected.includes("java"))
  generated.push([
    "sdks/debugbundle-java/debugbundle-java-core/src/main/resources/com/debugbundle/sdk/event-envelope.schema.json",
    content
  ]);
if (selected.includes("go"))
  generated.push(["sdks/debugbundle-go/internal/evidence/event-envelope.schema.json", content]);
if (selected.includes("dotnet"))
  generated.push([
    "sdks/debugbundle-dotnet/src/DebugBundle.Sdk/event-envelope.schema.json",
    content
  ]);
if (selected.includes("android"))
  generated.push([
    "sdks/debugbundle-android/debugbundle-android-core/src/main/resources/com/debugbundle/android/event-envelope.schema.json",
    content
  ]);
if (selected.includes("swift")) {
  const data = Buffer.from(JSON.stringify(schema), "utf8").toString("base64");
  const chunks = data.match(/.{1,512}/g) ?? [];
  if (chunks.length > 780) throw new Error("Embedded Swift schema needs a source-file split");
  generated.push([
    "sdks/debugbundle-swift/Sources/DebugBundle/DebugBundleCanonicalSchemaData.swift",
    `// Generated by scripts/sync-evidence-fixtures.ts. Do not edit by hand.
// Embedded contract data keeps SwiftPM and CocoaPods identical without capture-time resource IO.
import Foundation

enum DebugBundleCanonicalSchemaData {
    static func load() -> Data? {
        Data(base64Encoded: [
${chunks.map((chunk) => `            "${chunk}"`).join(",\n")}
        ].joined())
    }
}

`
  ]);
}
if (selected.includes("react_native")) {
  const chunks = JSON.stringify(schema).match(/.{1,1024}/gs) ?? [];
  if (chunks.length > 780)
    throw new Error("Embedded React Native schema needs a source-file split");
  generated.push([
    "sdks/debugbundle-react-native/src/event-schema-data.ts",
    `// Generated by scripts/sync-evidence-fixtures.ts. Do not edit by hand.\n// Plain contract data keeps the native JS runtime independent of schema-library versions.\nexport const eventSchemaData: unknown = JSON.parse([\n${chunks.map((chunk) => `  ${JSON.stringify(chunk)}`).join(",\n")}\n].join(""));\n`
  ]);
}

for (const [path, expected] of generated) {
  const target = resolve(path);
  if (process.argv.includes("--check")) {
    if ((await readFile(target, "utf8")) !== expected)
      throw new Error(`Stale evidence schema: ${path}`);
  } else {
    await mkdir(dirname(target), { recursive: true });
    await writeFile(target, expected);
  }
}
